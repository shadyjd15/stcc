// Applies to a job through the real public form. Usage: node scripts/e2e-apply.cjs <job-slug> <cv.pdf> <first> <last> <email> <years> <title> <answer:yes|no>
const { chromium } = require('playwright')
;(async () => {
  const [slug, cv, first, last, email, years, title, ans] = process.argv.slice(2)
  const base = process.env.BASE || 'http://localhost:3000'
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  page.setDefaultTimeout(180000)
  await page.goto(`${base}/careers/${slug}`, { waitUntil: 'networkidle' })
  await page.waitForTimeout(1500)
  const f = (n, v) => page.fill(`[name="${n}"]`, v)
  await f('firstName', first); await f('lastName', last); await f('email', email); await f('phone', '+966500000000')
  await f('location', 'Dammam, Saudi Arabia'); await f('currentTitle', title); await f('yearsExperience', years)
  await f('skills', 'Piping inspection, hydrotest, NDT')
  await page.setInputFiles('input[type="file"]', cv)
  const radios = page.locator(`input[type="radio"][value="${ans}"]`)
  for (let i = 0; i < (await radios.count()); i++) await radios.nth(i).check({ force: true })
  await page.check('[name="consent"]', { force: true })
  await page.click('button[type="submit"]')
  await page.waitForSelector('.success-panel, .field__error', { timeout: 120000 })
  console.log('RESULT:', (await page.locator('.success-panel, .field__error').first().innerText()).replace(/\s+/g, ' '))
  await page.screenshot({ path: '/tmp/shots/apply-result.png' })
  await browser.close()
})()
